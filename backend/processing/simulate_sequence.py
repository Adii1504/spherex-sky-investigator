"""Multi-Epoch SPHEREx Sequence Generator.

Generates a realistic multi-epoch observation sequence with fixed background stars
and a moving solar-system asteroid with known kinematics.

HARD RULE 1 COMPLIANCE:
All files generated by this script are clearly marked as:
"SYNTHETIC TEST DATA - NOT REAL ASTRONOMICAL MEASUREMENTS"

This unblocks Person 4 (FastAPI) and Person 3 (React UI) immediately while
waiting for real archive downloads.

Usage:
    python backend/processing/simulate_sequence.py [--out-dir backend/processing/sample_data/sequence]
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

from astropy.io import fits
from astropy.time import Time, TimeDelta
from astropy.wcs import WCS
import numpy as np


def generate_synthetic_epoch(
    out_path: Path,
    epoch_idx: int,
    obs_time_utc: str,
    asteroid_ra: float,
    asteroid_dec: float,
    stars_coords: list[tuple[float, float, float]],  # (ra, dec, flux)
    asteroid_flux: float = 8.5,
    center_ra: float = 150.0,
    center_dec: float = 2.0,
    size_px: int = 64,
    pixscale_arcsec: float = 6.16,
    noise_sigma: float = 0.05,
    seed: int = 42,
) -> Path:
    """Generate one synthetic SPHEREx Level 2 MEF cutout."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed + epoch_idx)

    # 1. Build WCS
    w = WCS(naxis=2)
    w.wcs.ctype = ["RA---TAN", "DEC--TAN"]
    w.wcs.crval = [center_ra, center_dec]
    w.wcs.crpix = [size_px / 2.0 + 0.5, size_px / 2.0 + 0.5]
    scale_deg = pixscale_arcsec / 3600.0
    w.wcs.cd = np.array([[-scale_deg, 0.0], [0.0, scale_deg]])

    # 2. Build Science Flux Image
    ny, nx = size_px, size_px
    image = np.full((ny, nx), 0.25, dtype=np.float64)  # Zodi background pedestal
    image += rng.normal(0.0, noise_sigma, size=(ny, nx))

    # Helper: inject 2D Gaussian point source
    yy, xx = np.indices((ny, nx))
    fwhm_px = 2.0
    sigma_px = fwhm_px / 2.355

    # Inject fixed background stars
    for s_ra, s_dec, s_flux in stars_coords:
        sx, sy = w.world_to_pixel_values(s_ra, s_dec)
        if -2 <= sx < nx + 2 and -2 <= sy < ny + 2:
            image += s_flux * np.exp(-((xx - sx) ** 2 + (yy - sy) ** 2) / (2.0 * sigma_px**2))

    # Inject moving asteroid
    ax, ay = w.world_to_pixel_values(asteroid_ra, asteroid_dec)
    if -2 <= ax < nx + 2 and -2 <= ay < ny + 2:
        image += asteroid_flux * np.exp(-((xx - ax) ** 2 + (yy - ay) ** 2) / (2.0 * sigma_px**2))

    # 3. Build Quality Flags & Variance
    flags = np.zeros((ny, nx), dtype=np.int32)
    # Inject a few bad pixels / cosmic rays away from sources
    flags[5, 5] = 1
    flags[10, 48] = 2

    variance = np.full((ny, nx), noise_sigma**2, dtype=np.float32)

    # 4. Construct HDUList
    pri_hdr = fits.Header()
    pri_hdr["TELESCOP"] = "SPHEREx"
    pri_hdr["INSTRUME"] = "SPHEREx"
    pri_hdr["VERSION"] = "SYNTHETIC TEST DATA v1.0"
    pri_hdr["OBJECT"] = "SYNTHETIC MOVING ASTEROID TEST DATA"
    pri_hdr["COMMENT"] = "SYNTHETIC TEST DATA - DO NOT USE FOR SCIENCE"
    pri_hdr["OBS_ID"] = f"SYNTH_EPOCH_{epoch_idx:02d}"
    primary_hdu = fits.PrimaryHDU(header=pri_hdr)

    img_hdr = fits.Header()
    img_hdr["EXTNAME"] = "IMAGE"
    img_hdr["BUNIT"] = "MJy/sr"
    img_hdr["DATE-OBS"] = obs_time_utc
    img_hdr["MJD-OBS"] = Time(obs_time_utc, scale="utc").mjd
    img_hdr["DETECTOR"] = 1
    img_hdr["WAVELEN"] = 1.05
    img_hdr.update(w.to_header())
    image_hdu = fits.ImageHDU(image.astype(np.float32), header=img_hdr, name="IMAGE")

    flags_hdu = fits.ImageHDU(flags, name="FLAGS")
    var_hdu = fits.ImageHDU(variance, name="VARIANCE")

    hdul = fits.HDUList([primary_hdu, image_hdu, flags_hdu, var_hdu])
    hdul.writeto(out_path, overwrite=True)
    return out_path


def generate_sequence(
    out_dir: str | Path = "backend/processing/sample_data/sequence",
    n_epochs: int = 4,
    speed_arcsec_per_hour: float = 12.0,
    time_step_hours: float = 2.0,
) -> list[Path]:
    """Generate a 4-epoch sequence of synthetic SPHEREx observations.

    Simulates a 12 arcsec/hour asteroid moving across stationary field stars.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    t0 = Time("2025-05-10T00:00:00.000", scale="utc")
    center_ra, center_dec = 150.0, 2.0
    cos_dec0 = math.cos(math.radians(center_dec))

    # Fixed background stars: (ra, dec, flux)
    fixed_stars = [
        (center_ra - 0.015, center_dec - 0.012, 12.0),
        (center_ra + 0.018, center_dec + 0.015, 7.5),
        (center_ra - 0.020, center_dec + 0.010, 5.0),
        (center_ra + 0.010, center_dec - 0.018, 9.0),
    ]

    # Asteroid initial position (starting slightly to the West and South of center)
    ast_ra0 = center_ra - 0.008
    ast_dec0 = center_dec - 0.008

    # Velocity: 12 arcsec/hour towards North-East (vx = 8.48, vy = 8.48 arcsec/hr)
    vx = speed_arcsec_per_hour / math.sqrt(2.0)
    vy = speed_arcsec_per_hour / math.sqrt(2.0)

    generated_paths: list[Path] = []
    print(f"Generating {n_epochs} synthetic SPHEREx epochs in {out_dir.resolve()}...")
    print(f"Injected Asteroid Speed: {speed_arcsec_per_hour:.1f} arcsec/hour (vx={vx:.2f}, vy={vy:.2f} ''/hr)")

    for ep_idx in range(n_epochs):
        dt_hr = ep_idx * time_step_hours
        t_curr = t0 + TimeDelta(dt_hr * 3600.0, format="sec")

        # Position at current epoch
        dx_arcsec = vx * dt_hr
        dy_arcsec = vy * dt_hr
        d_ra_deg = (dx_arcsec / 3600.0) / cos_dec0
        d_dec_deg = dy_arcsec / 3600.0

        ast_ra = ast_ra0 + d_ra_deg
        ast_dec = ast_dec0 + d_dec_deg

        filename = f"spherex_synth_epoch_{ep_idx + 1:02d}.fits"
        out_file = out_dir / filename

        generate_synthetic_epoch(
            out_path=out_file,
            epoch_idx=ep_idx,
            obs_time_utc=t_curr.isot,
            asteroid_ra=ast_ra,
            asteroid_dec=ast_dec,
            stars_coords=fixed_stars,
            asteroid_flux=8.5,
            center_ra=center_ra,
            center_dec=center_dec,
        )

        print(f"  [Epoch {ep_idx + 1}] {out_file.name}: t={t_curr.isot}, Asteroid at RA={ast_ra:.5f}, Dec={ast_dec:.5f}")
        generated_paths.append(out_file)

    print(f"[SUCCESS] Generated {len(generated_paths)} synthetic FITS files.")
    return generated_paths


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate synthetic SPHEREx multi-epoch sequence.")
    parser.add_argument("--out-dir", default="backend/processing/sample_data/sequence")
    parser.add_argument("--epochs", type=int, default=4)
    parser.add_argument("--speed", type=float, default=12.0)
    args = parser.parse_args()

    generate_sequence(out_dir=args.out_dir, n_epochs=args.epochs, speed_arcsec_per_hour=args.speed)


if __name__ == "__main__":
    main()
